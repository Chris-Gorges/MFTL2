"""Derive the API reference's Doxygen configuration from the project's template.

``docs/doxygen/Doxyfile.in`` is the one place this repository states what
Doxygen should do with its sources: which aliases the doc comments use, which
macros the preprocessor must not expand, what ``EXTRACT_STATIC`` is set to.
The Material site's API reference is generated from Doxygen XML by mkdoxy, and
if that run used a *different* configuration the two manuals would document
subtly different libraries -- an alias would come out as literal ``@collective``
text on one side and a rendered paragraph on the other.

So the template is read, flattened and handed to mkdoxy, exactly as
``build_docs.py`` and CMake hand it to Doxygen.  Only the output-format keys are
overridden, because mkdoxy wants XML and no HTML.

Flattening is needed because mkdoxy re-parses the file with a line-oriented
reader that keeps one value per key: Doxygen's ``+=`` accumulation (which the
seven MFTL aliases rely on) has to be collapsed into a single assignment first.
"""

from __future__ import annotations

import os
import re

_ASSIGN_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(\+?=)\s*(.*)$")
_CONTINUATION_RE = re.compile(r"\\\s*\n\s*")
_PLACEHOLDER_RE = re.compile(r"@([A-Z_][A-Z0-9_]*)@")

#: Keys forced to these values for the XML run.  Everything else is inherited.
#: ``INPUT`` and ``OUTPUT_DIRECTORY`` are absent on purpose -- mkdoxy overwrites
#: them itself from ``src-dirs`` and its cache directory.
XML_OVERRIDES: dict[str, str] = {
    "GENERATE_XML": "YES",
    "GENERATE_HTML": "NO",
    "GENERATE_LATEX": "NO",
    "XML_PROGRAMLISTING": "YES",
    # The Markdown corpus is rendered by the Material site itself (see
    # docs/mkdocs/gen_pages.py). Letting Doxygen read it here too would put a
    # second, differently-rendered copy of every guide page into the API
    # reference's "Related Pages".
    "FILE_PATTERNS": "*.c *.h *.dox",
    "FILTER_PATTERNS": "",
    "USE_MDFILE_AS_MAINPAGE": "",
    "LAYOUT_FILE": "",
    # Graphviz output is an HTML artefact; the XML run does not need it and it
    # is by far the slowest part of a Doxygen pass.
    "HAVE_DOT": "NO",
    "DOT_PATH": "",
    # The zero-warning criterion is enforced by build_docs.py --strict against
    # the real manual. Repeating it here would report every warning twice.
    "QUIET": "YES",
    "WARNINGS": "NO",
    "WARN_IF_UNDOCUMENTED": "NO",
    "WARN_IF_INCOMPLETE_DOC": "NO",
    "WARN_NO_PARAMDOC": "NO",
    "WARN_IF_UNDOC_ENUM_VAL": "NO",
    "WARN_LOGFILE": "",
}


def project_version(root: str, fallback: str = "6.0") -> str:
    """Read the version out of ``CMakeLists.txt``.

    :param root: repository root.
    :param fallback: value to use when the ``project()`` call cannot be read.
    :returns: the version string, e.g. ``"6.0"``.
    """
    path = os.path.join(root, "CMakeLists.txt")
    try:
        with open(path, encoding="utf-8") as handle:
            match = re.search(r"^project\s*\([^)]*VERSION\s+([0-9][0-9.]*)", handle.read(), re.MULTILINE)
    except OSError:
        return fallback
    return match.group(1) if match else fallback


def parse(text: str, substitutions: dict[str, str]) -> dict[str, str]:
    """Flatten a Doxyfile template into one value per key.

    :param text: contents of ``Doxyfile.in``.
    :param substitutions: values for the ``@PLACEHOLDER@`` tokens.
    :returns: the configuration as a dictionary, with ``+=`` accumulated.
    """
    text = _PLACEHOLDER_RE.sub(lambda m: substitutions.get(m.group(1), ""), text)
    text = _CONTINUATION_RE.sub(" ", text)

    config: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = _ASSIGN_RE.match(stripped)
        if match is None:
            continue
        key, operator, value = match.group(1), match.group(2), match.group(3).strip()
        if operator == "+=" and config.get(key):
            config[key] = f"{config[key]} {value}"
        else:
            config[key] = value
    return config


def render(config: dict[str, str]) -> str:
    """Serialise a configuration dictionary back into Doxyfile syntax.

    :param config: one value per key.
    :returns: the file contents.
    """
    header = (
        "# Generated by docs/mkdocs/doxyfile.py from docs/doxygen/Doxyfile.in.\n"
        "# Do not edit: edit the template, which the Doxygen manual uses too.\n\n"
    )
    body = "".join(f"{key:<24}= {value}\n" for key, value in config.items())
    return header + body


def write_api_doxyfile(root: str, destination: str) -> str:
    """Generate the Doxyfile mkdoxy should run for the API reference.

    :param root: repository root.
    :param destination: path of the file to write.
    :returns: the path written.
    """
    template = os.path.join(root, "docs", "doxygen", "Doxyfile.in")
    with open(template, encoding="utf-8") as handle:
        text = handle.read()

    config = parse(
        text,
        {
            "MFTL_VERSION": project_version(root),
            "MFTL_DOCS_SOURCE_DIR": root,
            "MFTL_DOCS_OUTPUT_DIR": os.path.dirname(destination),
            "MFTL_DOCS_HAVE_DOT": "NO",
            "MFTL_DOCS_DOT_PATH": "",
        },
    )
    config.update(XML_OVERRIDES)

    os.makedirs(os.path.dirname(destination), exist_ok=True)
    with open(destination, "w", encoding="utf-8") as handle:
        handle.write(render(config))
    return destination
